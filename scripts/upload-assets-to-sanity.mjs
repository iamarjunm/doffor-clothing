async function uploadImageToSanity(filename) {
  const filePath = path.join(IMAGES_DIR, filename);
  if (!fs.existsSync(filePath)) {
    console.warn(`  ⚠ Skipping missing file: ${filename}`);
    return null;
  }

  const bytes = fs.readFileSync(filePath);
  const url = `https://${PROJECT_ID}.api.sanity.io/v${API_VERSION}/assets/images/${DATASET}?filename=${encodeURIComponent(
    filename
  )}`;

  const res = await fetch(url, {
    method: 'POST',
    headers: {
      'Content-Type': 'image/jpeg',
      Authorization: `Bearer ${TOKEN}`,
    },
    body: bytes,
  });

  const data = await res.json().catch(() => ({}));
  if (!res.ok || !data?.document?._id) {
    throw new Error(`Upload failed for ${filename} (${res.status}): ${JSON.stringify(data)}`);
  }

  return {
    assetId: data.document._id,
    url: `${data.document.url}?auto=format&fit=max&w=1400&q=85`,
    rawUrl: data.document.url,
  };
}

function imgRef(assetMap, localPath, keyPrefix) {
  const entry = assetMap[localPath];
  if (!entry?.assetId) return undefined;
  return {
    _type: 'image',
    ...(keyPrefix ? { _key: keyPrefix } : {}),
    asset: { _type: 'reference', _ref: entry.assetId },
  };
}

async function mutateSanity(mutations) {
  const url = `https://${PROJECT_ID}.api.sanity.io/v${API_VERSION}/data/mutate/${DATASET}`;
  const res = await fetch(url, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      Authorization: `Bearer ${TOKEN}`,
    },
    body: JSON.stringify({ mutations }),
  });

  const data = await res.json().catch(() => ({}));
  if (!res.ok) {
    throw new Error(`Sanity mutate failed (${res.status}): ${JSON.stringify(data)}`);
  }
  return data;
}

